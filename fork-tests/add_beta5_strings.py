for locale, values in (("values", en), ("values-uk", uk), ("values-ru", ru)):
    path = res / locale / "fork_custom_text.xml"
    text = path.read_text(encoding="utf-8")
    missing = [key for key in values if f'name="{key}"' not in text]
    if len(missing) != len(values):
        raise SystemExit(f"{path}: expected all keys to be new, found {len(values) - len(missing)} existing")
    block = "\n".join(f'    <string name="{k}">{v}</string>' for k, v in values.items())
    if "</resources>" not in text:
        raise SystemExit(f"{path}: no closing resources tag")
    text = text.replace("</resources>", block + "\n</resources>")
    path.write_text(text, encoding="utf-8")
    print(f"updated {path} (+{len(values)})")
